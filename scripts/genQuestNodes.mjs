// scripts/genQuestNodes.mjs: writes functions/utils/bundledQuestNodes.js, the server's copy of every quest's topic
// list (id, kind, step count) that the classSummary trigger uses to decide "topic done" (G119).
// Run after ANY change to quest nodes: node scripts/genQuestNodes.mjs   (tests/questNodesSnapshot.test.mjs fails if stale)
import fs from "node:fs";
import { QUESTS } from "../data/quests/index.js";

export function snapshot() {
  const out = {};
  for (const m of QUESTS) out[m.QUEST_ID] = (m.nodes || []).map((n) => ({ id: n.id, kind: n.kind, stepCount: Array.isArray(n.steps) ? n.steps.length : 0 }));
  return out;
}

if (process.argv[1] && process.argv[1].endsWith("genQuestNodes.mjs")) {
  const body = `// functions/utils/bundledQuestNodes.js
// Server-side lightweight bundled quest node index for class summary triggers.
// GENERATED by scripts/genQuestNodes.mjs from data/quests/index.js: do not edit by hand.

const NODES_BY_QUEST = ${JSON.stringify(snapshot(), null, 2)};

function getBundledNodes(questId) {
  return NODES_BY_QUEST[questId] || null;
}

module.exports = { NODES_BY_QUEST, getBundledNodes };
`;
  fs.writeFileSync(new URL("../functions/utils/bundledQuestNodes.js", import.meta.url), body);
  console.log("bundledQuestNodes.js written:", Object.keys(snapshot()).join(", "));
}
